-- Migración no destructiva para sedes, cargos y vacantes de SIDOVI.
-- Ejecutar una sola vez conectado a la base configurada en .env.

CREATE TABLE IF NOT EXISTS sede (
    id_sede integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_sede varchar(80) NOT NULL UNIQUE,
    activa boolean NOT NULL DEFAULT true,
    creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cargo (
    id_cargo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cargo varchar(100) NOT NULL,
    descripcion_cargo text NOT NULL DEFAULT '',
    turnos varchar(120) NOT NULL DEFAULT '',
    id_sede integer NOT NULL REFERENCES sede(id_sede) ON UPDATE CASCADE ON DELETE RESTRICT,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT cargo_nombre_sede_uk UNIQUE (nombre_cargo, id_sede)
);

ALTER TABLE vacante ADD COLUMN IF NOT EXISTS id_sede integer;
ALTER TABLE vacante ADD COLUMN IF NOT EXISTS id_cargo integer;

