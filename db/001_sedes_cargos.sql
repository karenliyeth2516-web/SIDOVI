    ('Tunja'), ('Duitama'), ('Sogamoso'), ('Chiquinquirá'), ('Bogotá')
ON CONFLICT (nombre_sede) DO NOTHING;

-- Las vacantes antiguas se distribuyen de manera estable para no dejarlas sin sede.
WITH sedes_ordenadas AS (
    SELECT id_sede,
           ROW_NUMBER() OVER (
               ORDER BY ARRAY_POSITION(
                   ARRAY['Tunja', 'Duitama', 'Sogamoso', 'Chiquinquirá', 'Bogotá'],
                   nombre_sede
               )
           ) AS posicion
    FROM sede
    WHERE nombre_sede IN ('Tunja', 'Duitama', 'Sogamoso', 'Chiquinquirá', 'Bogotá')
)
UPDATE vacante v
SET id_sede = s.id_sede
FROM sedes_ordenadas s
WHERE v.id_sede IS NULL
