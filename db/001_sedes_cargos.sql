SELECT DISTINCT
    v.titulo,
    COALESCE(v.descripcion, ''),
    COALESCE(v.requisitos, ''),
    v.id_sede
FROM vacante v
WHERE v.titulo IS NOT NULL AND v.id_sede IS NOT NULL
