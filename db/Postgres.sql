BEGIN;

-- =========================== LIMPIEZA ======================================
-- Se elimina el esquema público para regenerarlo en un solo paso.
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;
GRANT ALL ON SCHEMA public TO postgres;
GRANT ALL ON SCHEMA public TO PUBLIC;

SET search_path = public, pg_catalog;

-- =========================== TABLAS ========================================

-- Sede: oficinas de Colviseg (clave por la que se filtran dashboard y vacantes).
CREATE TABLE sede (
    id_sede    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_sede varchar(80) NOT NULL UNIQUE,
    activa     boolean NOT NULL DEFAULT true,
    creado_en  timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Cargo: puesto operativo asociado a una sede.
CREATE TABLE cargo (
    id_cargo          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cargo      varchar(100) NOT NULL,
    descripcion_cargo text NOT NULL DEFAULT '',
    turnos            varchar(120) NOT NULL DEFAULT '',
    id_sede           integer NOT NULL REFERENCES sede(id_sede) ON UPDATE CASCADE ON DELETE RESTRICT,
    activo            boolean NOT NULL DEFAULT true,
    creado_en         timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT cargo_nombre_sede_uk UNIQUE (nombre_cargo, id_sede)
);
CREATE INDEX idx_cargo_id_sede ON cargo(id_sede);

-- Recursos Humanos: dueño de aspirantes seleccionados (requerido por el flujo
-- de entrevistas y por los fixtures de prueba).
CREATE TABLE recursos_humanos (
    id_rrhh      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rrhh  varchar(120) NOT NULL DEFAULT 'Recursos Humanos',
    activo       boolean NOT NULL DEFAULT true
);

-- Usuario: personal interno (RRHH y Gerente). El login usa nombre_completo,
-- contrasena_hash (bcrypt o texto), rol y activo.
CREATE TABLE usuario (
    id_usuario       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  varchar(120) NOT NULL,
    correo           varchar(120) NOT NULL UNIQUE,
    contrasena_hash  varchar(200) NOT NULL,
    rol              varchar(50) NOT NULL,
    activo           boolean NOT NULL DEFAULT true
);

-- Aspirante: candidato registrado por el formulario público o por RRHH.
CREATE TABLE aspirante (
    id_aspirante     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento   varchar(20)  NOT NULL DEFAULT 'CC',
    numero_documento varchar(30)  NOT NULL,
    nombre_completo  varchar(160) NOT NULL,
    correo           varchar(120) NOT NULL,
    telefono         varchar(30)  NOT NULL DEFAULT '',
    direccion        varchar(160) NOT NULL DEFAULT '',
    fecha_registro   date NOT NULL DEFAULT CURRENT_DATE,
    activo           boolean NOT NULL DEFAULT true,
    CONSTRAINT aspirante_documento_uk UNIQUE (tipo_documento, numero_documento)
);

-- Vacante: oferta laboral. Posee id_sede, id_cargo y nombre_cargo (caché de
-- lectura para listados sin JOIN, como espera server.js).
CREATE TABLE vacante (
    id_vacante         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo             varchar(160) NOT NULL,
    descripcion        text NOT NULL,
    requisitos         text NOT NULL DEFAULT '',
    fecha_publicacion  date NOT NULL DEFAULT CURRENT_DATE,
    estado             varchar(30) NOT NULL DEFAULT 'ABIERTA',
    id_usuario         integer REFERENCES usuario(id_usuario) ON DELETE SET NULL,
    id_sede            integer REFERENCES sede(id_sede) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_cargo           integer REFERENCES cargo(id_cargo) ON UPDATE CASCADE ON DELETE SET NULL,
    nombre_cargo       varchar(120) NOT NULL DEFAULT ''
);
CREATE INDEX idx_vacante_id_sede ON vacante(id_sede);
CREATE INDEX idx_vacante_id_cargo ON vacante(id_cargo);
CREATE INDEX idx_vacante_estado ON vacante(estado);

-- Postulacion: vínculo aspirante-vacante. El estado se guarda en la columna
-- "estado" (valores normalizados tipo EN_REVISION, ENTREVISTA, APROBADO...).
CREATE TABLE postulacion (
    id_postulacion    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aspirante      integer NOT NULL REFERENCES aspirante(id_aspirante) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_vacante        integer NOT NULL REFERENCES vacante(id_vacante) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_postulacion date NOT NULL DEFAULT CURRENT_DATE,
    estado            varchar(50) NOT NULL DEFAULT 'EN_REVISION'
);
CREATE INDEX idx_postulacion_id_aspirante ON postulacion(id_aspirante);
CREATE INDEX idx_postulacion_id_vacante ON postulacion(id_vacante);
CREATE INDEX idx_postulacion_estado ON postulacion(estado);

-- Triggers del flujo (mensaje de notificación y validación de postulación única).
CREATE FUNCTION mensaje_postulacion() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE NOTICE 'Nueva postulacion registrada';
    RETURN NEW;
END;
$$;

CREATE FUNCTION validar_postulacion_unica() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM postulacion
        WHERE id_aspirante = NEW.id_aspirante
          AND id_vacante = NEW.id_vacante
    ) THEN
        RAISE EXCEPTION 'El aspirante ya se ha postulado a esta vacante';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trigger_postulacion
    AFTER INSERT ON postulacion
    FOR EACH ROW EXECUTE FUNCTION mensaje_postulacion();

CREATE TRIGGER trigger_validar_postulacion
    BEFORE INSERT ON postulacion
    FOR EACH ROW EXECUTE FUNCTION validar_postulacion_unica();

-- Documento: hoja de vida o adjuntos del aspirante.
CREATE TABLE documento (
    id_documento     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_documento varchar(120) NOT NULL DEFAULT 'Documento',
    tipo_documento   varchar(50) NOT NULL DEFAULT 'PDF',
    archivo          text NOT NULL DEFAULT 'pendiente',
    id_aspirante     integer NOT NULL REFERENCES aspirante(id_aspirante) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_documento_id_aspirante ON documento(id_aspirante);

-- Aspirantes seleccionados: candidatos aprobados por RRHH que pasan a
-- entrevista. id_postulacion es UNIQUE para permitir ON CONFLICT id_postulacion.
CREATE TABLE aspirantes_seleccionados (
    id_seleccionado integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_postulacion  integer NOT NULL UNIQUE REFERENCES postulacion(id_postulacion) ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_seleccion date NOT NULL DEFAULT CURRENT_DATE,
    estado          varchar(60) NOT NULL DEFAULT 'SELECCIONADO_EN_PROCESO',
    id_rrhh         integer REFERENCES recursos_humanos(id_rrhh) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX idx_seleccionados_id_rrhh ON aspirantes_seleccionados(id_rrhh);

-- Entrevista: agenda de una entrevista para un seleccionado. Conserva el PK
-- id_entrevista (referenciado por evaluacion) y una UNIQUE en id_seleccionado
-- para que cada seleccionado tenga una sola fila.
CREATE TABLE entrevista (
    id_entrevista    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_seleccionado  integer NOT NULL UNIQUE REFERENCES aspirantes_seleccionados(id_seleccionado) ON UPDATE CASCADE ON DELETE CASCADE,
    id_postulacion   integer REFERENCES postulacion(id_postulacion) ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_entrevista date NOT NULL,
    modalidad        varchar(30) NOT NULL DEFAULT 'Presencial',
    estado           varchar(30) NOT NULL DEFAULT 'PROGRAMADA',
    observacion      text NOT NULL DEFAULT '',
    id_gerente       integer REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX idx_entrevista_id_gerente ON entrevista(id_gerente);

-- Evaluacion: calificación gerencial ligada a una entrevista.
CREATE TABLE evaluacion (
    id_evaluacion  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preguntas      text NOT NULL,
    calificacion   integer NOT NULL DEFAULT 0,
    comentarios    text NOT NULL DEFAULT '',
    id_entrevista  integer NOT NULL REFERENCES entrevista(id_entrevista) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_evaluacion_id_entrevista ON evaluacion(id_entrevista);

-- Evidencia: adjuntos (fotos, credenciales) del proceso de postulación.
CREATE TABLE evidencia (
    id_evidencia    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_evidencia  varchar(50) NOT NULL DEFAULT 'Foto',
    descripcion     text NOT NULL DEFAULT '',
    archivo         text NOT NULL DEFAULT 'pendiente',
    id_postulacion  integer NOT NULL REFERENCES postulacion(id_postulacion) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Contrato: vínculo laboral del postulante aprobado.
CREATE TABLE contrato (
    id_contrato    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_postulacion integer NOT NULL UNIQUE REFERENCES postulacion(id_postulacion) ON UPDATE CASCADE ON DELETE CASCADE,
    fecha_inicio   date NOT NULL,
    fecha_fin      date,
    tipo_contrato  varchar(50) NOT NULL DEFAULT 'Término Fijo',
    salario        numeric(12,2) NOT NULL DEFAULT 1423500,
    estado         varchar(30) NOT NULL DEFAULT 'Borrador',
    observaciones  text NOT NULL DEFAULT '',
    creado_en      timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_contrato_estado ON contrato(estado);

-- Notificacion: avisos del proceso (usada por la vista y reportes).
CREATE TABLE notificacion (
    id_notificacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje         text NOT NULL,
    leida           boolean NOT NULL DEFAULT false,
    creado_en       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario      integer REFERENCES usuario(id_usuario) ON UPDATE CASCADE ON DELETE SET NULL
);

-- =========================== VISTAS ========================================

-- Historial de cada aspirante: total de postulaciones y última fecha.
CREATE VIEW vista_historial_aspirante AS
SELECT
    a.id_aspirante,
    a.tipo_documento,
    a.numero_documento,
    a.nombre_completo,
    a.correo,
    a.telefono,
    COUNT(p.id_postulacion)::int AS total_postulaciones,
    MAX(p.fecha_postulacion) AS ultima_postulacion
FROM aspirante a
LEFT JOIN postulacion p ON p.id_aspirante = a.id_aspirante
GROUP BY a.id_aspirante;

-- Estadísticas de postulaciones por mes.
CREATE VIEW vista_estadistica_postulaciones AS
SELECT
    ROW_NUMBER() OVER (ORDER BY DATE_TRUNC('month', fecha_postulacion) DESC)::int AS periodo_id,
    'MES'::varchar AS tipo_periodo,
    DATE_TRUNC('month', fecha_postulacion)::date AS periodo_inicio,
    (DATE_TRUNC('month', fecha_postulacion) + INTERVAL '1 month - 1 day')::date AS periodo_fin,
    COUNT(*)::int AS total_postulaciones
FROM postulacion
GROUP BY DATE_TRUNC('month', fecha_postulacion);

