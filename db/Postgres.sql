-- Ejecutar una sola vez conectado a la base SIDOVI:
--   psql -U postgres -d SIDOVI -f db/Postgres.sql
--
-- Contenido: esquema completo + datos demo (sedes, cargos, usuarios con rol,
-- vacantes de seguridad, aspirantes, postulaciones, entrevistas, contratos).
